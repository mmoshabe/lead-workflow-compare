"""Generate the JavaScript for the Zapier "Code by Zapier" step (see CONTRACT.md).

    python3 zapier/build_code.py > zapier/code-step.js

Input Data fields to map in Zapier: raw_body (from the "Catch Raw Hook" trigger: the whole lead as JSON, so no
field-by-field mapping) and api_key (paste your Anthropic key there, never in the code).
The step calls Claude with exactly the request from scripts/build_request.py and returns flat fields for the
Google Sheets row, the filter (next_step) and the Slack text.
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))
import build_request as br  # noqa: E402

CODE = r"""// Generated by zapier/build_code.py; edit the repo, not this step.
const FIELDS = __FIELDS__;
const TEMPLATE = __TEMPLATE__;
const lead = inputData.raw_body ? JSON.parse(inputData.raw_body) : inputData;   // Catch Raw Hook: one JSON field
const lines = FIELDS.filter(f => f !== 'message').map(f => `${f}: ${lead[f] || '(not given)'}`);
const content = '<enquiry>\n' + lines.join('\n') + `\nmessage: ${lead.message || ''}\n</enquiry>`;

const res = await fetch('https://api.anthropic.com/v1/messages', {
  method: 'POST',
  headers: { 'x-api-key': inputData.api_key, 'anthropic-version': '2026-10-21', 'content-type': 'application/json' },
  body: JSON.stringify({ ...TEMPLATE, messages: [{ role: 'user', content }] }),
});
const r = await res.json();
if (!res.ok) throw new Error(`Claude ${res.status}: ${(r.error || {}).message || 'request failed'}`);

let ai;
try { ai = JSON.parse((r.content || []).find(b => b.type === 'text').text); }   // pick the text block by type
catch (e) { ai = { fit: 'medium', service: 'none', budget_band: 'unknown', urgency: 'normal', next_step: 'email',
                   summary: 'AI output unreadable: check this lead by hand', missing_info: [], red_flags: ['AI output unreadable'],
                   follow_up_subject: '', follow_up_body: '' }; }
const u = r.usage || {};
const bits = [lead.company, lead.budget, lead.timeline].filter(Boolean).join(', ');
return {
  received: new Date().toISOString(), lead_id: lead.lead_id || '', name: lead.name || '', email: lead.email || '',
  company: lead.company || '', fit: ai.fit, service: ai.service, budget_band: ai.budget_band, urgency: ai.urgency,
  next_step: ai.next_step, summary: ai.summary, missing_info: (ai.missing_info || []).join('; '),
  red_flags: (ai.red_flags || []).join('; '), follow_up_subject: ai.follow_up_subject, follow_up_body: ai.follow_up_body,
  tokens: `${u.input_tokens || 0}/${u.output_tokens || 0}`,
  slack_text: `[zapier] *New lead (${ai.fit} fit, ${ai.next_step})*: ${lead.name}${bits ? ', ' + bits : ''}.\n${ai.summary}\nDraft reply is in the leads sheet (row for ${lead.lead_id}).`,
};
"""


def code() -> str:
    template = br.request({})
    template.pop("messages")
    return CODE.replace("__FIELDS__", json.dumps(br.FIELDS)).replace("__TEMPLATE__", json.dumps(template, ensure_ascii=False))


if __name__ == "__main__":
    sys.stdout.write(code())
